"""
FinEdge Fraud Detection Service — Step 13: Updated Integration Tests

Tests cover four scenarios:
  1. Health endpoint — asserts new modelStatus field exists (either value valid)
  2. Fraud check — ML model mode (artifacts present) — shape/type assertions only
  3. Fraud check — STUB fallback mode (ML_ARTIFACTS_DIR pointed at empty/nonexistent dir)
  4. Fraud check — Unauthenticated request (unchanged)

NOTE ON TEST DESIGN (Step 13 update):
======================================
The previous test (test_fraud_check_stub_authenticated) asserted riskScore == 85.0.
This is only valid in stub mode. In ML mode the score is a model probability × 100,
which depends on the artifact and feature vector — it cannot be hardcoded.

Strategy:
  - ML mode tests: assert shape, types, valid enum values, modelVersion != "stub-v0"
  - Stub mode tests: assert original deterministic scores (85.0 / 55.0 / 15.0)
                     using ML_ARTIFACTS_DIR override to force stub fallback

STUB FALLBACK FORCING:
========================
The model_loader module uses a module-level _registry dict populated at startup.
To force stub mode in tests without restarting the app, we directly reset the
_registry["loaded"] flag via monkeypatching. This is the simplest approach for
a college project — a production service would use dependency injection.
"""

import base64
import os
from datetime import datetime, timedelta
from unittest.mock import patch

import jwt
import pytest
from fastapi.testclient import TestClient

from app.config.settings import settings
from app.main import app
