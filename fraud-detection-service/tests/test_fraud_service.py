# 2. Fraud check — ML model mode (real synthetic artifacts)
# ---------------------------------------------------------------------------

def test_fraud_check_ml_mode_response_shape():
    """
    When ML artifacts are present, fraud/check must return a valid, well-shaped response.
    We do NOT assert a specific riskScore — ML output depends on the artifact.
    """
    from app.model import model_loader
    if not model_loader.is_model_loaded():
        pytest.skip(
            "ML model not loaded (artifacts not present or load failed). "
            "Run ml/training/train_models.py first, then re-run tests."
        )

    token = get_test_jwt()
    headers = {"Authorization": f"Bearer {token}"}
    payload = {
        "transactionRef": "TXN-ML-001",
        "type": "TRANSFER",
        "fromAccountNumber": "ACC-1001",
        "toAccountNumber": "ACC-1002",
        "amount": 15000.0,
        "initiatedByUsername": "testuser",
        "timestamp": "2024-03-15T02:30:00Z",   # late-night — should trigger indicator
    }
    response = client.post("/api/v1/fraud/check", json=payload, headers=headers)
    assert response.status_code == 200

    data = response.json()
    assert data["transactionRef"] == "TXN-ML-001"
    assert 0.0 <= data["riskScore"] <= 100.0, "riskScore must be in [0, 100]"
    assert data["decision"] in ("LOW_RISK", "REVIEW", "HIGH_RISK")
    assert isinstance(data["indicators"], list)
    assert len(data["indicators"]) > 0
    assert data["modelVersion"] != "stub-v0", "ML mode must not report stub-v0 version"
    assert "evaluatedAt" in data


