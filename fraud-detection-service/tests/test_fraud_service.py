# 3. Fraud check — STUB fallback mode (ML_ARTIFACTS_DIR forced to nonexistent)
# ---------------------------------------------------------------------------

def test_fraud_check_stub_fallback_high_risk():
    """
    With ML model forcibly disabled (stub mode), the original amount-threshold
    heuristic must still return 85.0 / HIGH_RISK for amount > $10,000.
    """
    from app.model import model_loader

    # Temporarily force stub mode by patching the registry
    original_loaded = model_loader._registry["loaded"]
    original_version = model_loader._registry["model_version"]
    try:
        model_loader._registry["loaded"] = False
        model_loader._registry["model_version"] = "stub-v0"

        token = get_test_jwt()
        headers = {"Authorization": f"Bearer {token}"}
        payload = {
            "transactionRef": "TXN-STUB-100",
            "type": "TRANSFER",
            "fromAccountNumber": "1001",
            "toAccountNumber": "1002",
            "amount": 15000.0,
            "initiatedByUsername": "testuser",
        }
        response = client.post("/api/v1/fraud/check", json=payload, headers=headers)
        assert response.status_code == 200
        data = response.json()
        assert data["transactionRef"] == "TXN-STUB-100"
        assert data["decision"] == "HIGH_RISK"
        assert data["riskScore"] == 85.0
        assert data["modelVersion"] == "stub-v0"
    finally:
        # Always restore original state
        model_loader._registry["loaded"] = original_loaded
        model_loader._registry["model_version"] = original_version


