client = TestClient(app)

# Path to real synthetic artifacts generated by Step 12
REAL_ARTIFACTS_DIR = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "..", "ml", "artifacts")
)
NONEXISTENT_ARTIFACTS_DIR = "/nonexistent/path/to/artifacts"


# ---------------------------------------------------------------------------
# JWT helper
# ---------------------------------------------------------------------------

def get_test_jwt() -> str:
    try:
        key = base64.b64decode(settings.JWT_SECRET)
    except Exception:
        key = settings.JWT_SECRET.encode("utf-8")

    payload = {
        "sub": "testuser",
        "role": "CUSTOMER",
        "exp": datetime.utcnow() + timedelta(hours=1)
    }
    return jwt.encode(payload, key, algorithm="HS256")


