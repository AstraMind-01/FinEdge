# ---------------------------------------------------------------------------
# 5. Model loader unit test — graceful fallback on missing artifacts
# ---------------------------------------------------------------------------

def test_model_loader_graceful_fallback_on_missing_dir():
    """
    load_model() pointed at a nonexistent directory must NOT raise an exception.
    Service remains in stub mode (_registry["loaded"] == False after the call).
    """
    from app.model import model_loader

    # Save current state
    original_registry = dict(model_loader._registry)
    try:
        # Reset to unloaded state
        model_loader._registry.update({
            "loaded": False, "model": None, "preprocessor": None,
            "model_name": None, "model_version": "stub-v0",
            "preprocessor_type": None, "metadata": {},
        })
        # This must not raise
        model_loader.load_model(NONEXISTENT_ARTIFACTS_DIR)
        assert model_loader._registry["loaded"] is False, \
            "Registry must remain unloaded when artifacts dir is missing"
        assert model_loader.is_model_loaded() is False
    finally:
        model_loader._registry.update(original_registry)
